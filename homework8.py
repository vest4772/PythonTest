def show_message():
    print("изучаю дектораторы с чатом гпт")

show_message()


# Задача №8
# Лекция №8: Функции
# Тема: Декораторы и аргументы функций

# 1. Создай декоратор log_function.
# 2. Он должен принимать функцию в качестве аргумента.
# 3. Внутри создай вложенную функцию wrapper.
# 4. wrapper должна:
#    - вывести "Функция запущена";
#    - вызвать исходную функцию;
#    - вывести "Функция завершена".
# 5. Верни wrapper через return.
# 6. Создай функцию greet, которая принимает аргумент name.
# 7. Внутри greet выведи приветствие с именем.
# 8. Примени декоратор log_function к greet.
# 9. Вызови greet("Алексей").

# Ожидаемый результат:
# Функция запущена
# Привет, Алексей!
# Функция завершена

print("---------- Задача №8 ----------")

def log_function(function):
    def wrapper(*args):
        print("Функция запущена")
        function(*args)
        print("Функция завершена")
    return wrapper

@log_function
def gret(name):
    print(f"Привет, {name}")

gret(name)