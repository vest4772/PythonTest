# Задача №6
# Лекция №8: Функции
# Тема: Декораторы

# 1. Создай функцию decorator.
# 2. Она должна принимать другую функцию в качестве аргумента.
# 3. Внутри decorator создай вложенную функцию wrapper.
# 4. wrapper должна:
#    - вывести "Начало выполнения";
#    - вызвать переданную функцию;
#    - вывести "Конец выполнения".
# 5. Верни wrapper из decorator через return.
# 6. Создай функцию say_hello, которая выводит "Привет!".
# 7. Передай say_hello в decorator и вызови полученную функцию.

# Ожидаемый результат:
# Начало выполнения
# Привет!
# Конец выполнения

print("---------- Задача №6 ----------")

def decorator(function):
    def test():
        print("Начало")
        function()
        print("Конец")
    return test

@decorator
def say_hello():
    print("Hello World")

say_hello()

